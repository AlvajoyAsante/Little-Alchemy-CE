const AlchemyItem *alchemy_item(AlchemyItemId id) {
    return id < ITEM_TABLE_SIZE && ITEMS[id].name != NULL ? &ITEMS[id] : NULL;
}

AlchemyItemId alchemy_find_item(const char *name) {
    size_t low = 0;
    size_t high = ITEM_COUNT;

    if (name == NULL) {
        return ALCHEMY_INVALID_ITEM;
    }

    while (low < high) {
        size_t middle = low + (high - low) / 2;
        AlchemyItemId id = NAME_INDEX[middle];
        int comparison = compare_names(name, ITEMS[id].name);

        if (comparison == 0) {
            return id;
        }
        if (comparison < 0) {
            high = middle;
        } else {
            low = middle + 1;
        }
    }
    return ALCHEMY_INVALID_ITEM;
}

static int compare_pair(
    AlchemyItemId first,
    AlchemyItemId second,
    const AlchemyRecipe *recipe
) {
    if (first != recipe->ingredient1) {
        return first < recipe->ingredient1 ? -1 : 1;
    }
    if (second != recipe->ingredient2) {
        return second < recipe->ingredient2 ? -1 : 1;
    }
    return 0;
}

size_t alchemy_combine(
    AlchemyItemId first,
    AlchemyItemId second,
    AlchemyItemId *results,
    size_t capacity
) {
    size_t low = 0;
    size_t high = RECIPE_COUNT;
    size_t count = 0;

    if (alchemy_item(first) == NULL || alchemy_item(second) == NULL) {
        return 0;
    }
    if (first > second) {
        AlchemyItemId temporary = first;
        first = second;
        second = temporary;
    }

    while (low < high) {
        size_t middle = low + (high - low) / 2;
        if (compare_pair(first, second, &RECIPES[middle]) <= 0) {
            high = middle;
        } else {
            low = middle + 1;
        }
    }

    while (low + count < RECIPE_COUNT &&
           compare_pair(first, second, &RECIPES[low + count]) == 0) {
        if (results != NULL && count < capacity) {
            results[count] = RECIPES[low + count].result;
        }
        count++;
    }
    return count;
}

size_t alchemy_combine_names(
    const char *first,
    const char *second,
    AlchemyItemId *results,
    size_t capacity
) {
    AlchemyItemId first_id = alchemy_find_item(first);
    AlchemyItemId second_id = alchemy_find_item(second);
    return alchemy_combine(first_id, second_id, results, capacity);
}

size_t alchemy_recipes_for(
    AlchemyItemId result,
    AlchemyRecipe *recipes,
    size_t capacity
) {
    size_t low = 0;
    size_t high = RECIPE_COUNT;
    size_t count = 0;

    if (alchemy_item(result) == NULL) {
        return 0;
    }

    while (low < high) {
        size_t middle = low + (high - low) / 2;
        if (RECIPES[RESULT_INDEX[middle]].result >= result) {
            high = middle;
        } else {
            low = middle + 1;
        }
    }

    while (low + count < RECIPE_COUNT &&
           RECIPES[RESULT_INDEX[low + count]].result == result) {
        if (recipes != NULL && count < capacity) {
            recipes[count] = RECIPES[RESULT_INDEX[low + count]];
        }
        count++;
    }
    return count;
}
