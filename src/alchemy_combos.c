static int compare_names(const char *query, const char *item_name) {
    while (*query != '\0' && *item_name != '\0') {
        unsigned char left = (unsigned char)*query++;
        unsigned char right = (unsigned char)*item_name++;

        if (left == ' ' || left == '_') {
            left = '-';
        }
        left = (unsigned char)tolower(left);

        if (left != right) {
            return left < right ? -1 : 1;
        }
    }
    if (*query == *item_name) {
        return 0;
    }
    return *query == '\0' ? -1 : 1;
}

