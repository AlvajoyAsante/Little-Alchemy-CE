/* Element sprites are stored ZX7-compressed inside the appvars, so they are
 * decompressed on demand into a single-sprite cache. The cache is only filled
 * when a sprite is actually drawn, so undiscovered items never occupy RAM.
 *
 * gfx_rletsprite_t only declares a 2-byte header, so we size the cache for a
 * full 32x32 RLET sprite (2-byte header + worst-case 32*32 data = 1026 bytes)
 * to avoid zx7_Decompress overflowing into adjacent memory. */
#define ELEMENT_SPRITE_CACHE_SIZE (2 + 32 * 32)
static uint8_t decompressed_sprite[ELEMENT_SPRITE_CACHE_SIZE];
static uint16_t decompressed_item_id = 0xFFFF;

const gfx_rletsprite_t *element_sprite(AlchemyItemId item_id)
{
    ElementSpriteLocation location;
    const void *compressed = NULL;

    if (item_id >= 582) {
        return NULL;
    }

    if (item_id == decompressed_item_id) {
        return (const gfx_rletsprite_t *)decompressed_sprite;
    }

    location = SPRITE_LOCATIONS[item_id];
    switch (location.pack) {
        case 1: compressed = ALCHM00_appvar[location.entry]; break;
        case 2: compressed = ALCHM01_appvar[location.entry]; break;
        case 3: compressed = ALCHM02_appvar[location.entry]; break;
        case 4: compressed = ALCHM03_appvar[location.entry]; break;
        case 5: compressed = ALCHM04_appvar[location.entry]; break;
        case 6: compressed = ALCHM05_appvar[location.entry]; break;
        case 7: compressed = ALCHM06_appvar[location.entry]; break;
        case 8: compressed = ALCHM07_appvar[location.entry]; break;
        case 9: compressed = ALCHM08_appvar[location.entry]; break;
        case 10: compressed = ALCHM09_appvar[location.entry]; break;
        default: return NULL;
    }

    zx7_Decompress(decompressed_sprite, compressed);
    decompressed_item_id = item_id;
    return (const gfx_rletsprite_t *)decompressed_sprite;
}

